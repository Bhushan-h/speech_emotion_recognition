"""### Feature Extraction
We will extract the following features from each audio file:
1. **ZCR (Zero Crossing Rate)**: The rate at which the signal changes from positive to negative or back.
2. **RMS (Root Mean Square) Energy**: Represents the loudness of the signal.
3. **MFCC (Mel-Frequency Cepstral Coefficients)**: A representation of the short-term power spectrum of a sound.
"""

def extract_features(data, sr):
    # ZCR
    result = np.array([])
    zcr = np.mean(librosa.feature.zero_crossing_rate(y=data).T, axis=0)
    result = np.hstack((result, zcr))

    # RMS Energy
    rms = np.mean(librosa.feature.rms(y=data).T, axis=0)
    result = np.hstack((result, rms))

    # MFCC
    mfcc = np.mean(librosa.feature.mfcc(y=data, sr=sr).T, axis=0)
    result = np.hstack((result, mfcc))

    return result

